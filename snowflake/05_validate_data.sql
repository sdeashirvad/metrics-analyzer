-- Reconciliation for the published tables after 04_reseed_and_snapshot.sql commits.
-- The first statement is a count grid. The block then fails the script when this workbook's
-- approved checks do not hold. Run against METRICS_ANALYZER.DQ, not against staging.
-- Staging is gated inside 04 before any active row is deleted.

USE DATABASE METRICS_ANALYZER;
USE SCHEMA DQ;

SELECT 'DQ_CONTROL_DEFINITIONS' AS check_name, COUNT(*) AS actual, 36 AS expected FROM DQ_CONTROL_DEFINITIONS
UNION ALL
SELECT 'DQ_RESULTS', COUNT(*), 1722 FROM DQ_RESULTS
UNION ALL
SELECT 'DQ_RESULTS_BY_DESK', COUNT(*), 4536 FROM DQ_RESULTS_BY_DESK
UNION ALL
SELECT 'DQ_EXCEPTIONS', COUNT(*), 1560 FROM DQ_EXCEPTIONS
UNION ALL
SELECT 'DESK_HIERARCHY', COUNT(*), 9 FROM DESK_HIERARCHY
UNION ALL
SELECT 'CHANGE_INCIDENT_EVENTS', COUNT(*), 12 FROM CHANGE_INCIDENT_EVENTS
UNION ALL
SELECT 'ANALYST_COMMENTARY', COUNT(*), 12 FROM ANALYST_COMMENTARY
UNION ALL
SELECT 'DQ_CONTROL_SNAPSHOT', COUNT(*), 36 FROM DQ_CONTROL_SNAPSHOT
UNION ALL
SELECT 'DQ_DATASET_STATE', COUNT(*), 1 FROM DQ_DATASET_STATE
UNION ALL
SELECT 'snapshot_red', COUNT_IF(RAG_STATUS = 'Red'), 5 FROM DQ_CONTROL_SNAPSHOT
UNION ALL
SELECT 'snapshot_amber', COUNT_IF(RAG_STATUS = 'Amber'), 2 FROM DQ_CONTROL_SNAPSHOT
UNION ALL
SELECT 'snapshot_green', COUNT_IF(RAG_STATUS = 'Green'), 29 FROM DQ_CONTROL_SNAPSHOT
UNION ALL
SELECT 'open_exceptions', COUNT_IF(STATUS = 'Open'), 722 FROM DQ_EXCEPTIONS
UNION ALL
SELECT 'desk_controls', COUNT(DISTINCT CONTROL_ID), 8 FROM DQ_RESULTS_BY_DESK
UNION ALL
SELECT 'planted_stories', COUNT_IF(PLANTED_STORY IS NOT NULL), 5 FROM DQ_CONTROL_DEFINITIONS
UNION ALL
SELECT 'planted_story_max_length', COALESCE(MAX(LENGTH(PLANTED_STORY)), -1), 102 FROM DQ_CONTROL_DEFINITIONS;

-- Offending keys. Each query should return zero rows.
SELECT CONTROL_ID
FROM DQ_CONTROL_DEFINITIONS
GROUP BY CONTROL_ID
HAVING COUNT(*) > 1;

SELECT RESULT_ID
FROM DQ_RESULTS
GROUP BY RESULT_ID
HAVING COUNT(*) > 1;

SELECT CONTROL_ID, METRIC_DATE
FROM DQ_RESULTS
GROUP BY CONTROL_ID, METRIC_DATE
HAVING COUNT(*) > 1;

SELECT CONTROL_ID, METRIC_DATE, DESK_ID
FROM DQ_RESULTS_BY_DESK
GROUP BY CONTROL_ID, METRIC_DATE, DESK_ID
HAVING COUNT(*) > 1;

SELECT COMMENTARY_DATE, CONTROL_ID
FROM ANALYST_COMMENTARY
GROUP BY COMMENTARY_DATE, CONTROL_ID
HAVING COUNT(*) > 1;

SELECT CONTROL_ID
FROM DQ_RESULTS
MINUS
SELECT CONTROL_ID
FROM DQ_CONTROL_DEFINITIONS;

SELECT desk.CONTROL_ID, desk.METRIC_DATE, desk.FAILED, result.FAILED_RECORDS, desk.TOTAL, result.TOTAL_RECORDS
FROM (
  SELECT CONTROL_ID, METRIC_DATE,
         SUM(FAILED_RECORDS) AS FAILED,
         SUM(TOTAL_RECORDS) AS TOTAL
  FROM DQ_RESULTS_BY_DESK
  GROUP BY CONTROL_ID, METRIC_DATE
) desk
JOIN DQ_RESULTS result
  ON result.CONTROL_ID = desk.CONTROL_ID
 AND result.METRIC_DATE = desk.METRIC_DATE
WHERE desk.FAILED <> result.FAILED_RECORDS
   OR desk.TOTAL <> result.TOTAL_RECORDS;

SELECT result.RESULT_ID, result.CONTROL_ID, result.METRIC_DATE, result.PASS_RATE_PCT, result.RAG_STATUS
FROM DQ_RESULTS result
JOIN DQ_CONTROL_DEFINITIONS definition
  ON definition.CONTROL_ID = result.CONTROL_ID
WHERE result.RAG_STATUS <> CASE
  WHEN result.PASS_RATE_PCT >= definition.GREEN_THRESHOLD THEN 'Green'
  WHEN result.PASS_RATE_PCT >= definition.AMBER_THRESHOLD THEN 'Amber'
  ELSE 'Red'
END;

SELECT COUNT(*) AS dataset_state_rows_not_active
FROM DQ_DATASET_STATE
WHERE STATE_ID <> 1
   OR LOAD_STATUS <> 'SUCCEEDED';

SELECT snapshot.CONTROL_ID, snapshot.CONTROL_DATA_VERSION, snapshot.DATASET_VERSION, state.ACTIVE_DATASET_VERSION
FROM DQ_CONTROL_SNAPSHOT snapshot
CROSS JOIN DQ_DATASET_STATE state
WHERE snapshot.CONTROL_DATA_VERSION < 1
   OR snapshot.DATASET_VERSION <> state.ACTIVE_DATASET_VERSION
   OR snapshot.CALCULATION_VERSION <> 'dq-rag-v1';

SELECT CONTROL_ID, PASS_RATE_PCT, FAILED_RECORDS, TOTAL_RECORDS, FIRST_RED_DATE, RAG_STATUS
FROM DQ_CONTROL_SNAPSHOT
WHERE CONTROL_ID = 'DQ-001'
  AND (
    PASS_RATE_PCT <> 97.3110
    OR FAILED_RECORDS <> 5999
    OR TOTAL_RECORDS <> 223085
    OR FIRST_RED_DATE <> DATE '2026-10-14'
    OR RAG_STATUS <> 'Red'
  );

-- Five validation questions. Keep these here until they have been executed in Snowflake.
-- Question 1: latest portfolio is 5 red, 2 amber, 29 green (grid above).
-- Question 2: DQ-001 latest row (query above should return zero rows).
-- Question 3: DQ-001 desk sum on 2026-10-28.
SELECT result.FAILED_RECORDS AS control_failed,
       SUM(desk.FAILED_RECORDS) AS desk_failed,
       COUNT(*) AS desk_rows
FROM DQ_RESULTS result
JOIN DQ_RESULTS_BY_DESK desk
  ON desk.CONTROL_ID = result.CONTROL_ID
 AND desk.METRIC_DATE = result.METRIC_DATE
WHERE result.CONTROL_ID = 'DQ-001'
  AND result.METRIC_DATE = DATE '2026-10-28'
GROUP BY result.FAILED_RECORDS;

-- Question 4: open exceptions = 722 (grid above).
-- Question 5: DQ-020 README story versus the 2026-09-08 commentary.
SELECT definition.PLANTED_STORY, commentary.ANALYST_COMMENTARY
FROM DQ_CONTROL_DEFINITIONS definition
LEFT JOIN ANALYST_COMMENTARY commentary
  ON commentary.CONTROL_ID = definition.CONTROL_ID
 AND commentary.COMMENTARY_DATE = DATE '2026-09-08'
WHERE definition.CONTROL_ID = 'DQ-020';

DECLARE
  failure_list VARCHAR;
BEGIN
  SELECT LISTAGG(check_name, ', ') WITHIN GROUP (ORDER BY check_name)
    INTO :failure_list
  FROM (
    SELECT 'definition_count' AS check_name WHERE (SELECT COUNT(*) FROM DQ_CONTROL_DEFINITIONS) <> 36
    UNION ALL SELECT 'result_count' WHERE (SELECT COUNT(*) FROM DQ_RESULTS) <> 1722
    UNION ALL SELECT 'desk_result_count' WHERE (SELECT COUNT(*) FROM DQ_RESULTS_BY_DESK) <> 4536
    UNION ALL SELECT 'exception_count' WHERE (SELECT COUNT(*) FROM DQ_EXCEPTIONS) <> 1560
    UNION ALL SELECT 'desk_count' WHERE (SELECT COUNT(*) FROM DESK_HIERARCHY) <> 9
    UNION ALL SELECT 'event_count' WHERE (SELECT COUNT(*) FROM CHANGE_INCIDENT_EVENTS) <> 12
    UNION ALL SELECT 'commentary_count' WHERE (SELECT COUNT(*) FROM ANALYST_COMMENTARY) <> 12
    UNION ALL SELECT 'snapshot_count' WHERE (SELECT COUNT(*) FROM DQ_CONTROL_SNAPSHOT) <> 36
    UNION ALL SELECT 'state_count' WHERE (SELECT COUNT(*) FROM DQ_DATASET_STATE) <> 1
    UNION ALL SELECT 'snapshot_red' WHERE (SELECT COUNT_IF(RAG_STATUS = 'Red') FROM DQ_CONTROL_SNAPSHOT) <> 5
    UNION ALL SELECT 'snapshot_amber' WHERE (SELECT COUNT_IF(RAG_STATUS = 'Amber') FROM DQ_CONTROL_SNAPSHOT) <> 2
    UNION ALL SELECT 'snapshot_green' WHERE (SELECT COUNT_IF(RAG_STATUS = 'Green') FROM DQ_CONTROL_SNAPSHOT) <> 29
    UNION ALL SELECT 'open_exceptions' WHERE (SELECT COUNT_IF(STATUS = 'Open') FROM DQ_EXCEPTIONS) <> 722
    UNION ALL SELECT 'desk_controls' WHERE (SELECT COUNT(DISTINCT CONTROL_ID) FROM DQ_RESULTS_BY_DESK) <> 8
    UNION ALL SELECT 'planted_stories' WHERE (SELECT COUNT_IF(PLANTED_STORY IS NOT NULL) FROM DQ_CONTROL_DEFINITIONS) <> 5
    UNION ALL SELECT 'planted_story_max_length' WHERE (SELECT MAX(LENGTH(PLANTED_STORY)) FROM DQ_CONTROL_DEFINITIONS) <> 102
    UNION ALL SELECT 'metric_date_range' WHERE (SELECT MIN(METRIC_DATE) FROM DQ_RESULTS) <> DATE '2026-08-03' OR (SELECT MAX(METRIC_DATE) FROM DQ_RESULTS) <> DATE '2026-10-28'
    UNION ALL SELECT 'duplicate_grain' WHERE EXISTS (SELECT 1 FROM DQ_RESULTS GROUP BY CONTROL_ID, METRIC_DATE HAVING COUNT(*) > 1)
    UNION ALL SELECT 'duplicate_desk_id' WHERE EXISTS (SELECT 1 FROM DESK_HIERARCHY GROUP BY DESK_ID HAVING COUNT(*) > 1)
    UNION ALL SELECT 'duplicate_desk_result_id' WHERE EXISTS (SELECT 1 FROM DQ_RESULTS_BY_DESK GROUP BY RESULT_ID HAVING COUNT(*) > 1)
    UNION ALL SELECT 'duplicate_exception_id' WHERE EXISTS (SELECT 1 FROM DQ_EXCEPTIONS GROUP BY EXCEPTION_ID HAVING COUNT(*) > 1)
    UNION ALL SELECT 'duplicate_trade_id' WHERE EXISTS (SELECT 1 FROM DQ_EXCEPTIONS GROUP BY TRADE_ID HAVING COUNT(*) > 1)
    UNION ALL SELECT 'duplicate_event_id' WHERE EXISTS (SELECT 1 FROM CHANGE_INCIDENT_EVENTS GROUP BY EVENT_ID HAVING COUNT(*) > 1)
    UNION ALL SELECT 'definition_without_result' WHERE EXISTS (
      SELECT 1 FROM DQ_CONTROL_DEFINITIONS definition
      WHERE NOT EXISTS (SELECT 1 FROM DQ_RESULTS result WHERE result.CONTROL_ID = definition.CONTROL_ID)
    )
    UNION ALL SELECT 'desk_without_parent_result' WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS_BY_DESK desk
      WHERE NOT EXISTS (
        SELECT 1 FROM DQ_RESULTS result
        WHERE result.CONTROL_ID = desk.CONTROL_ID AND result.METRIC_DATE = desk.METRIC_DATE
      )
    )
    UNION ALL SELECT 'desk_record_counts' WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS_BY_DESK
      WHERE TOTAL_RECORDS <= 0 OR FAILED_RECORDS < 0 OR FAILED_RECORDS > TOTAL_RECORDS
    )
    UNION ALL SELECT 'pass_rate_bounds' WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
      UNION ALL
      SELECT 1 FROM DQ_RESULTS_BY_DESK WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
    )
    UNION ALL SELECT 'desk_sum_mismatch' WHERE EXISTS (
      SELECT 1
      FROM (
        SELECT CONTROL_ID, METRIC_DATE, SUM(FAILED_RECORDS) AS FAILED, SUM(TOTAL_RECORDS) AS TOTAL
        FROM DQ_RESULTS_BY_DESK
        GROUP BY CONTROL_ID, METRIC_DATE
      ) desk
      JOIN DQ_RESULTS result
        ON result.CONTROL_ID = desk.CONTROL_ID AND result.METRIC_DATE = desk.METRIC_DATE
      WHERE desk.FAILED <> result.FAILED_RECORDS OR desk.TOTAL <> result.TOTAL_RECORDS
    )
    UNION ALL SELECT 'result_rag_mismatch' WHERE EXISTS (
      SELECT 1
      FROM DQ_RESULTS result
      JOIN DQ_CONTROL_DEFINITIONS definition ON definition.CONTROL_ID = result.CONTROL_ID
      WHERE result.RAG_STATUS <> CASE
        WHEN result.PASS_RATE_PCT >= definition.GREEN_THRESHOLD THEN 'Green'
        WHEN result.PASS_RATE_PCT >= definition.AMBER_THRESHOLD THEN 'Amber'
        ELSE 'Red'
      END
    )
    UNION ALL SELECT 'state_status' WHERE EXISTS (
      SELECT 1 FROM DQ_DATASET_STATE WHERE STATE_ID <> 1 OR LOAD_STATUS <> 'SUCCEEDED'
    )
    UNION ALL SELECT 'snapshot_version' WHERE EXISTS (
      SELECT 1
      FROM DQ_CONTROL_SNAPSHOT snapshot
      CROSS JOIN DQ_DATASET_STATE state
      WHERE snapshot.CONTROL_DATA_VERSION < 1
         OR snapshot.DATASET_VERSION <> state.ACTIVE_DATASET_VERSION
         OR snapshot.CALCULATION_VERSION <> 'dq-rag-v1'
    )
    UNION ALL SELECT 'dq_001_latest' WHERE EXISTS (
      SELECT 1 FROM DQ_CONTROL_SNAPSHOT
      WHERE CONTROL_ID = 'DQ-001'
        AND (
          PASS_RATE_PCT <> 97.3110
          OR FAILED_RECORDS <> 5999
          OR TOTAL_RECORDS <> 223085
          OR FIRST_RED_DATE <> DATE '2026-10-14'
          OR RAG_STATUS <> 'Red'
        )
    )
    UNION ALL SELECT 'dq_001_desk_sum' WHERE NOT EXISTS (
      SELECT 1
      FROM (
        SELECT result.FAILED_RECORDS AS control_failed,
               SUM(desk.FAILED_RECORDS) AS desk_failed,
               COUNT(*) AS desk_rows
        FROM DQ_RESULTS result
        JOIN DQ_RESULTS_BY_DESK desk
          ON desk.CONTROL_ID = result.CONTROL_ID
         AND desk.METRIC_DATE = result.METRIC_DATE
        WHERE result.CONTROL_ID = 'DQ-001'
          AND result.METRIC_DATE = DATE '2026-10-28'
        GROUP BY result.FAILED_RECORDS
      ) summed
      WHERE summed.control_failed = 5999
        AND summed.desk_failed = 5999
        AND summed.desk_rows = 9
    )
    UNION ALL SELECT 'dq_020_story_versus_commentary' WHERE NOT EXISTS (
      SELECT 1
      FROM DQ_CONTROL_DEFINITIONS definition
      JOIN ANALYST_COMMENTARY commentary
        ON commentary.CONTROL_ID = definition.CONTROL_ID
       AND commentary.COMMENTARY_DATE = DATE '2026-09-08'
      WHERE definition.CONTROL_ID = 'DQ-020'
        AND definition.PLANTED_STORY = 'Commodities booking migration not mapped to risk feed; Commodities and Securitised are the hotspots'
        AND commentary.ANALYST_COMMENTARY LIKE '%Treasury & Funding%'
    )
    UNION ALL SELECT 'volume_share' WHERE ABS((SELECT SUM(VOLUME_SHARE) FROM DESK_HIERARCHY) - 1) > 0.000001
  );

  IF (failure_list IS NOT NULL) THEN
    EXECUTE IMMEDIATE
      'DECLARE validation_failed EXCEPTION (-20003, ''Published data failed reconciliation: '
      || failure_list
      || '''); BEGIN RAISE validation_failed; END;';
  END IF;
  RETURN 'Published data matches the approved workbook contract.';
END;
