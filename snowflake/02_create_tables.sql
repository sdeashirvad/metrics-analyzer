-- Ten permanent tables from the approved contract.
-- Constraints are NOT ENFORCED. The reseed preflight owns uniqueness.
-- IF NOT EXISTS will not alter a table that already exists.

USE DATABASE METRICS_ANALYZER;
USE SCHEMA DQ;

CREATE TABLE IF NOT EXISTS DQ_CONTROL_DEFINITIONS (
  CONTROL_ID              VARCHAR(16)   NOT NULL COMMENT 'Workbook control_id. Example DQ-001.',
  CONTROL_NAME            VARCHAR(200)  NOT NULL,
  DQ_DIMENSION            VARCHAR(32)   NOT NULL COMMENT 'App domain. Example Validity.',
  REGULATION              VARCHAR(80)   NOT NULL,
  REGULATORY_REPORT       VARCHAR(80)   NOT NULL,
  CRITICAL_DATA_ELEMENT   VARCHAR(80)   NOT NULL,
  SOURCE_SYSTEM           VARCHAR(80)   NOT NULL,
  FREQUENCY               VARCHAR(16)   NOT NULL COMMENT 'Daily, Weekly, or Monthly.',
  GREEN_THRESHOLD         NUMBER(18,4)  NOT NULL COMMENT 'Rounded to 4 dp on load.',
  AMBER_THRESHOLD         NUMBER(18,4)  NOT NULL COMMENT 'Rounded to 4 dp on load.',
  SEVERITY                VARCHAR(16)   NOT NULL,
  CHECK_LOGIC             VARCHAR(1000) NOT NULL,
  BCBS239_PRINCIPLE       VARCHAR(80)   NOT NULL,
  OWNER_ROLE              VARCHAR(80)   NOT NULL,
  PLANTED_STORY           VARCHAR(256)  COMMENT 'README planted_story cell, unchanged. Null except five controls. Max observed 102. Supplied story context, not an established fact.',
  CONSTRAINT PK_DQ_CONTROL_DEFINITIONS PRIMARY KEY (CONTROL_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DESK_HIERARCHY (
  DESK_ID         VARCHAR(16)  NOT NULL,
  DESK_NAME       VARCHAR(80)  NOT NULL,
  BUSINESS_LINE   VARCHAR(40)  NOT NULL,
  PRIMARY_REGION  VARCHAR(16)  NOT NULL,
  VOLUME_SHARE    NUMBER(8,4)  NOT NULL COMMENT 'Fraction of book volume, not a percent.',
  CONSTRAINT PK_DESK_HIERARCHY PRIMARY KEY (DESK_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_RESULTS (
  RESULT_ID       VARCHAR(16)  NOT NULL COMMENT 'R-sequence. Not a desk result id.',
  METRIC_DATE     DATE         NOT NULL COMMENT 'Converted from Excel serial or loaded from an ISO date.',
  CONTROL_ID      VARCHAR(16)  NOT NULL,
  FREQUENCY       VARCHAR(16)  NOT NULL,
  TOTAL_RECORDS   NUMBER(18,0) NOT NULL,
  FAILED_RECORDS  NUMBER(18,0) NOT NULL,
  PASS_RATE_PCT   NUMBER(18,4) NOT NULL COMMENT 'Supplied percentage, rounded to 4 dp.',
  RAG_STATUS      VARCHAR(16)  NOT NULL COMMENT 'Workbook token: Green, Amber, Red.',
  CONSTRAINT PK_DQ_RESULTS PRIMARY KEY (RESULT_ID) NOT ENFORCED,
  CONSTRAINT UQ_DQ_RESULTS_CONTROL_DATE UNIQUE (CONTROL_ID, METRIC_DATE) NOT ENFORCED,
  CONSTRAINT FK_DQ_RESULTS_CONTROL FOREIGN KEY (CONTROL_ID)
    REFERENCES DQ_CONTROL_DEFINITIONS (CONTROL_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_RESULTS_BY_DESK (
  RESULT_ID       VARCHAR(16)  NOT NULL COMMENT 'O-sequence. Does not reference DQ_RESULTS.RESULT_ID.',
  METRIC_DATE     DATE         NOT NULL,
  CONTROL_ID      VARCHAR(16)  NOT NULL,
  DESK_ID         VARCHAR(16)  NOT NULL,
  TOTAL_RECORDS   NUMBER(18,0) NOT NULL,
  FAILED_RECORDS  NUMBER(18,0) NOT NULL,
  PASS_RATE_PCT   NUMBER(18,4) NOT NULL,
  RAG_STATUS      VARCHAR(16)  NOT NULL,
  CONSTRAINT PK_DQ_RESULTS_BY_DESK PRIMARY KEY (RESULT_ID) NOT ENFORCED,
  CONSTRAINT UQ_DQ_DESK_GRAIN UNIQUE (CONTROL_ID, METRIC_DATE, DESK_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_DESK_CONTROL FOREIGN KEY (CONTROL_ID)
    REFERENCES DQ_CONTROL_DEFINITIONS (CONTROL_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_DESK_DESK FOREIGN KEY (DESK_ID)
    REFERENCES DESK_HIERARCHY (DESK_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_DESK_RESULT FOREIGN KEY (CONTROL_ID, METRIC_DATE)
    REFERENCES DQ_RESULTS (CONTROL_ID, METRIC_DATE) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_EXCEPTIONS (
  EXCEPTION_ID     VARCHAR(16)  NOT NULL,
  EXCEPTION_DATE   DATE         NOT NULL,
  CONTROL_ID       VARCHAR(16)  NOT NULL,
  DESK_ID          VARCHAR(16)  NOT NULL,
  TRADE_ID         VARCHAR(32)  NOT NULL,
  FIELD_NAME       VARCHAR(80)  NOT NULL,
  OFFENDING_VALUE  VARCHAR(200) NOT NULL,
  FAILURE_REASON   VARCHAR(500) NOT NULL,
  SEVERITY         VARCHAR(16)  NOT NULL,
  STATUS           VARCHAR(32)  NOT NULL,
  AGEING_DAYS      NUMBER(6,0)  NOT NULL COMMENT 'Supplied. Not derived from the date.',
  ASSIGNED_TEAM    VARCHAR(80)  NOT NULL,
  CONSTRAINT PK_DQ_EXCEPTIONS PRIMARY KEY (EXCEPTION_ID) NOT ENFORCED,
  CONSTRAINT UQ_DQ_EXCEPTIONS_TRADE UNIQUE (TRADE_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_EX_CONTROL FOREIGN KEY (CONTROL_ID)
    REFERENCES DQ_CONTROL_DEFINITIONS (CONTROL_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_EX_DESK FOREIGN KEY (DESK_ID)
    REFERENCES DESK_HIERARCHY (DESK_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS CHANGE_INCIDENT_EVENTS (
  EVENT_ID             VARCHAR(16)   NOT NULL,
  EVENT_DATE           DATE          NOT NULL COMMENT 'ISO text in the workbook.',
  EVENT_TYPE           VARCHAR(32)   NOT NULL,
  DESK_IDS             VARCHAR(200)  NOT NULL COMMENT 'Comma-separated desk ids, or the token ALL.',
  DESCRIPTION          VARCHAR(2000) NOT NULL,
  RELATED_CONTROL_ID   VARCHAR(16)   NOT NULL,
  CONSTRAINT PK_CHANGE_INCIDENT_EVENTS PRIMARY KEY (EVENT_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_EVENT_CONTROL FOREIGN KEY (RELATED_CONTROL_ID)
    REFERENCES DQ_CONTROL_DEFINITIONS (CONTROL_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS ANALYST_COMMENTARY (
  COMMENTARY_DATE       DATE          NOT NULL,
  CONTROL_ID            VARCHAR(16)   NOT NULL,
  RAG_AT_TIME           VARCHAR(16)   NOT NULL,
  ANALYST_COMMENTARY    VARCHAR(4000) NOT NULL,
  ROOT_CAUSE_CATEGORY   VARCHAR(80)   NOT NULL COMMENT 'Supplied label, not a confirmed cause.',
  PATH_TO_GREEN         VARCHAR(500)  NOT NULL COMMENT 'Supplied path, not an approved plan.',
  AUTHOR_ROLE           VARCHAR(80)   NOT NULL,
  CONSTRAINT UQ_DQ_COMMENTARY UNIQUE (COMMENTARY_DATE, CONTROL_ID) NOT ENFORCED,
  CONSTRAINT FK_DQ_COMMENTARY_CONTROL FOREIGN KEY (CONTROL_ID)
    REFERENCES DQ_CONTROL_DEFINITIONS (CONTROL_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_DATASET_STATE (
  STATE_ID                 NUMBER(1,0)   NOT NULL COMMENT 'Always 1. One row.',
  ACTIVE_DATASET_VERSION   NUMBER(10,0)  NOT NULL COMMENT 'Increments only when a reseed commits.',
  SOURCE_LABEL             VARCHAR(500)  NOT NULL COMMENT 'Example SMARTS_DQ_mock_data.xlsx.',
  LOAD_STATUS              VARCHAR(16)   NOT NULL COMMENT 'SUCCEEDED on the stored row.',
  STARTED_AT               TIMESTAMP_NTZ NOT NULL COMMENT 'Reseed script start, written only when the reseed commits.',
  COMPLETED_AT             TIMESTAMP_NTZ NOT NULL,
  DEFINITION_ROWS          NUMBER(10,0)  NOT NULL,
  RESULT_ROWS              NUMBER(10,0)  NOT NULL,
  DESK_RESULT_ROWS         NUMBER(10,0)  NOT NULL,
  EXCEPTION_ROWS           NUMBER(10,0)  NOT NULL,
  DESK_ROWS                NUMBER(10,0)  NOT NULL,
  EVENT_ROWS               NUMBER(10,0)  NOT NULL,
  COMMENTARY_ROWS          NUMBER(10,0)  NOT NULL,
  METRIC_DATE_MIN          DATE          NOT NULL,
  METRIC_DATE_MAX          DATE          NOT NULL,
  CONSTRAINT PK_DQ_DATASET_STATE PRIMARY KEY (STATE_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_CONTROL_SNAPSHOT (
  CONTROL_ID                 VARCHAR(16)   NOT NULL,
  CONTROL_DATA_VERSION       NUMBER(10,0)  NOT NULL COMMENT 'Per-control version. Starts at 1. A full reseed increments every rebuilt control. A later incremental load increments only affected controls. This is the AI cache validity key.',
  DATASET_VERSION            NUMBER(10,0)  NOT NULL COMMENT 'Dataset provenance. ACTIVE_DATASET_VERSION at calculation time. Not the AI cache key.',
  CALCULATION_VERSION        VARCHAR(32)   NOT NULL COMMENT 'dq-rag-v1.',
  CALCULATED_AT              TIMESTAMP_NTZ NOT NULL,
  AS_OF_DATE                 DATE          NOT NULL COMMENT 'Max metric_date for this control.',
  PASS_RATE_PCT              NUMBER(18,4)  NOT NULL COMMENT 'Supplied rate of that row, at 4 dp.',
  RAG_STATUS                 VARCHAR(16)   NOT NULL COMMENT 'Supplied RAG of that row, checked against the rule.',
  FAILED_RECORDS             NUMBER(18,0)  NOT NULL,
  TOTAL_RECORDS              NUMBER(18,0)  NOT NULL,
  GREEN_THRESHOLD            NUMBER(18,4)  NOT NULL COMMENT 'Copied from the definition at calculation time.',
  AMBER_THRESHOLD            NUMBER(18,4)  NOT NULL,
  FREQUENCY                  VARCHAR(16)   NOT NULL,
  FIRST_RED_DATE             DATE          COMMENT 'Null when the series has no Red row.',
  LAST_RED_DATE              DATE,
  POINT_COUNT                NUMBER(10,0)  NOT NULL,
  HAS_DESK_SPLIT             BOOLEAN       NOT NULL,
  RECOVERED                  BOOLEAN       NOT NULL COMMENT 'Latest Green and FIRST_RED_DATE is present.',
  EXCEPTION_COUNT            NUMBER(10,0)  NOT NULL,
  OPEN_EXCEPTION_COUNT       NUMBER(10,0)  NOT NULL COMMENT 'STATUS = Open.',
  OLDEST_OPEN_AGEING_DAYS    NUMBER(10,0)  COMMENT 'Max supplied ageing among Open rows.',
  EVENT_COUNT                NUMBER(10,0)  NOT NULL,
  COMMENTARY_COUNT           NUMBER(10,0)  NOT NULL,
  CONSTRAINT PK_DQ_CONTROL_SNAPSHOT PRIMARY KEY (CONTROL_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS DQ_AI_ANALYSIS_RUNS (
  RUN_ID                VARCHAR(36)   NOT NULL COMMENT 'UUID.',
  CONTROL_ID            VARCHAR(16)   NOT NULL,
  ANALYSIS_TYPE         VARCHAR(32)   NOT NULL COMMENT 'SUMMARY or INVESTIGATION.',
  CONTROL_DATA_VERSION  NUMBER(10,0)  NOT NULL COMMENT 'Matches the snapshot version used for this run. Cache validity key.',
  DATASET_VERSION       NUMBER(10,0)  NOT NULL COMMENT 'Dataset provenance at generation time. Not the cache key.',
  PROMPT_VERSION        VARCHAR(64)   NOT NULL,
  CALCULATION_VERSION   VARCHAR(32)   NOT NULL COMMENT 'dq-rag-v1.',
  MODEL                 VARCHAR(128)  NOT NULL COMMENT 'Part of the cache key.',
  STATUS                VARCHAR(16)   NOT NULL COMMENT 'COMPLETED or FAILED. Insert once. COMPLETED means validation passed.',
  RESULT                VARIANT       COMMENT 'Structured JSON. Null when FAILED.',
  ERROR_TEXT            VARCHAR(2000),
  GENERATED_AT          TIMESTAMP_NTZ NOT NULL,
  CONSTRAINT PK_DQ_AI_ANALYSIS_RUNS PRIMARY KEY (RUN_ID) NOT ENFORCED
);

COMMENT ON TABLE DQ_AI_ANALYSIS_RUNS IS
  'Append-only. Reuse the latest COMPLETED non-null RESULT whose CONTROL_ID and CONTROL_DATA_VERSION match the current snapshot, and whose ANALYSIS_TYPE, PROMPT_VERSION, CALCULATION_VERSION, and MODEL match. DATASET_VERSION is provenance only. There is no unique constraint on that key.';
