-- Full reseed of the seven source tables and rebuild of DQ_CONTROL_SNAPSHOT.
-- Run this file as one script, in a session that does not already have an open transaction.
-- Staging must already be loaded (see README.md). This script does not COPY files and does not run DDL.
--
-- Order inside the transaction:
--   1. DELETE and INSERT the seven source tables.
--   2. MERGE DQ_CONTROL_SNAPSHOT. An existing control keeps its version and adds 1.
--      A new control starts at 1. Rows for controls that no longer exist are deleted.
--   3. Update DQ_DATASET_STATE immediately before COMMIT.
-- A failure rolls the transaction back, so the dataset version stays aligned with the published rows.

USE DATABASE METRICS_ANALYZER;
USE SCHEMA DQ;

DECLARE
  in_txn BOOLEAN DEFAULT FALSE;
  new_version NUMBER(10,0);
  started_at TIMESTAMP_NTZ;
  source_label VARCHAR DEFAULT 'SMARTS_DQ_mock_data.xlsx';
  failure_list VARCHAR;
  published_list VARCHAR;
  snapshot_gap NUMBER(10,0);
  snapshot_mismatch NUMBER(10,0);
  snapshot_count NUMBER(10,0);
  snapshot_missing NUMBER(10,0);
BEGIN
  started_at := SYSDATE();

  SELECT LISTAGG(check_name, ', ') WITHIN GROUP (ORDER BY check_name)
    INTO :failure_list
  FROM (
    SELECT 'definition_count' AS check_name
    WHERE (SELECT COUNT(*) FROM STG_DQ_CONTROL_DEFINITIONS) <> 36
    UNION ALL
    SELECT 'result_count'
    WHERE (SELECT COUNT(*) FROM STG_DQ_RESULTS) <> 1722
    UNION ALL
    SELECT 'desk_result_count'
    WHERE (SELECT COUNT(*) FROM STG_DQ_RESULTS_BY_DESK) <> 4536
    UNION ALL
    SELECT 'exception_count'
    WHERE (SELECT COUNT(*) FROM STG_DQ_EXCEPTIONS) <> 1560
    UNION ALL
    SELECT 'desk_count'
    WHERE (SELECT COUNT(*) FROM STG_DESK_HIERARCHY) <> 9
    UNION ALL
    SELECT 'event_count'
    WHERE (SELECT COUNT(*) FROM STG_CHANGE_INCIDENT_EVENTS) <> 12
    UNION ALL
    SELECT 'commentary_count'
    WHERE (SELECT COUNT(*) FROM STG_ANALYST_COMMENTARY) <> 12
    UNION ALL
    SELECT 'metric_date_range'
    WHERE (SELECT MIN(METRIC_DATE) FROM STG_DQ_RESULTS) <> DATE '2026-08-03'
       OR (SELECT MAX(METRIC_DATE) FROM STG_DQ_RESULTS) <> DATE '2026-10-28'
    UNION ALL
    SELECT 'duplicate_definition'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS GROUP BY CONTROL_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_result_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS GROUP BY RESULT_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_result_grain'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS GROUP BY CONTROL_ID, METRIC_DATE HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_desk_grain'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK
      GROUP BY CONTROL_ID, METRIC_DATE, DESK_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_desk_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DESK_HIERARCHY GROUP BY DESK_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_desk_result_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK GROUP BY RESULT_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_exception_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_EXCEPTIONS GROUP BY EXCEPTION_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_trade_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_EXCEPTIONS GROUP BY TRADE_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_event_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_CHANGE_INCIDENT_EVENTS GROUP BY EVENT_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'duplicate_commentary'
    WHERE EXISTS (
      SELECT 1 FROM STG_ANALYST_COMMENTARY
      GROUP BY COMMENTARY_DATE, CONTROL_ID HAVING COUNT(*) > 1
    )
    UNION ALL
    SELECT 'result_id_namespace'
    WHERE EXISTS (
      SELECT RESULT_ID FROM STG_DQ_RESULTS
      INTERSECT
      SELECT RESULT_ID FROM STG_DQ_RESULTS_BY_DESK
    )
    UNION ALL
    SELECT 'orphan_result_control'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS r
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS d WHERE d.CONTROL_ID = r.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'orphan_desk_control'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK r
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS d WHERE d.CONTROL_ID = r.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'orphan_exception_control'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_EXCEPTIONS e
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS d WHERE d.CONTROL_ID = e.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'orphan_event_control'
    WHERE EXISTS (
      SELECT 1 FROM STG_CHANGE_INCIDENT_EVENTS e
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS d WHERE d.CONTROL_ID = e.RELATED_CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'orphan_commentary_control'
    WHERE EXISTS (
      SELECT 1 FROM STG_ANALYST_COMMENTARY c
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS d WHERE d.CONTROL_ID = c.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'orphan_desk_id'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK r
      WHERE NOT EXISTS (SELECT 1 FROM STG_DESK_HIERARCHY h WHERE h.DESK_ID = r.DESK_ID)
      UNION ALL
      SELECT 1 FROM STG_DQ_EXCEPTIONS e
      WHERE NOT EXISTS (SELECT 1 FROM STG_DESK_HIERARCHY h WHERE h.DESK_ID = e.DESK_ID)
    )
    UNION ALL
    SELECT 'event_desk_token'
    WHERE EXISTS (
      SELECT 1
      FROM STG_CHANGE_INCIDENT_EVENTS e,
           LATERAL SPLIT_TO_TABLE(e.DESK_IDS, ',') token
      WHERE TRIM(token.VALUE) <> 'ALL'
        AND NOT EXISTS (
          SELECT 1 FROM STG_DESK_HIERARCHY h WHERE h.DESK_ID = TRIM(token.VALUE)
        )
    )
    UNION ALL
    SELECT 'desk_sum_mismatch'
    WHERE EXISTS (
      SELECT 1
      FROM (
        SELECT CONTROL_ID, METRIC_DATE,
               SUM(FAILED_RECORDS) AS FAILED,
               SUM(TOTAL_RECORDS) AS TOTAL
        FROM STG_DQ_RESULTS_BY_DESK
        GROUP BY CONTROL_ID, METRIC_DATE
      ) desk
      JOIN STG_DQ_RESULTS result
        ON result.CONTROL_ID = desk.CONTROL_ID
       AND result.METRIC_DATE = desk.METRIC_DATE
      WHERE desk.FAILED <> result.FAILED_RECORDS
         OR desk.TOTAL <> result.TOTAL_RECORDS
    )
    UNION ALL
    SELECT 'result_rag_mismatch'
    WHERE EXISTS (
      SELECT 1
      FROM STG_DQ_RESULTS r
      JOIN STG_DQ_CONTROL_DEFINITIONS d ON d.CONTROL_ID = r.CONTROL_ID
      WHERE r.RAG_STATUS <> CASE
        WHEN r.PASS_RATE_PCT >= d.GREEN_THRESHOLD THEN 'Green'
        WHEN r.PASS_RATE_PCT >= d.AMBER_THRESHOLD THEN 'Amber'
        ELSE 'Red'
      END
    )
    UNION ALL
    SELECT 'desk_rag_mismatch'
    WHERE EXISTS (
      SELECT 1
      FROM STG_DQ_RESULTS_BY_DESK r
      JOIN STG_DQ_CONTROL_DEFINITIONS d ON d.CONTROL_ID = r.CONTROL_ID
      WHERE r.RAG_STATUS <> CASE
        WHEN r.PASS_RATE_PCT >= d.GREEN_THRESHOLD THEN 'Green'
        WHEN r.PASS_RATE_PCT >= d.AMBER_THRESHOLD THEN 'Amber'
        ELSE 'Red'
      END
    )
    UNION ALL
    SELECT 'frequency_mismatch'
    WHERE EXISTS (
      SELECT 1
      FROM STG_DQ_RESULTS r
      JOIN STG_DQ_CONTROL_DEFINITIONS d ON d.CONTROL_ID = r.CONTROL_ID
      WHERE r.FREQUENCY <> d.FREQUENCY
    )
    UNION ALL
    SELECT 'threshold_order'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_CONTROL_DEFINITIONS
      WHERE GREEN_THRESHOLD <= AMBER_THRESHOLD
    )
    UNION ALL
    SELECT 'record_counts'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS
      WHERE TOTAL_RECORDS <= 0 OR FAILED_RECORDS < 0 OR FAILED_RECORDS > TOTAL_RECORDS
    )
    UNION ALL
    SELECT 'desk_record_counts'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK
      WHERE TOTAL_RECORDS <= 0 OR FAILED_RECORDS < 0 OR FAILED_RECORDS > TOTAL_RECORDS
    )
    UNION ALL
    SELECT 'pass_rate_bounds'
    WHERE EXISTS (
      SELECT 1 FROM STG_DQ_RESULTS
      WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
      UNION ALL
      SELECT 1 FROM STG_DQ_RESULTS_BY_DESK
      WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
    )
    UNION ALL
    SELECT 'definition_without_result'
    WHERE EXISTS (
      SELECT 1
      FROM STG_DQ_CONTROL_DEFINITIONS definition
      WHERE NOT EXISTS (
        SELECT 1 FROM STG_DQ_RESULTS result WHERE result.CONTROL_ID = definition.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'desk_without_parent_result'
    WHERE EXISTS (
      SELECT 1
      FROM STG_DQ_RESULTS_BY_DESK desk
      WHERE NOT EXISTS (
        SELECT 1
        FROM STG_DQ_RESULTS result
        WHERE result.CONTROL_ID = desk.CONTROL_ID
          AND result.METRIC_DATE = desk.METRIC_DATE
      )
    )
    UNION ALL
    SELECT 'volume_share'
    WHERE ABS((SELECT COALESCE(SUM(VOLUME_SHARE), 0) FROM STG_DESK_HIERARCHY) - 1) > 0.000001
    UNION ALL
    SELECT 'planted_story'
    WHERE (SELECT COUNT(*) FROM STG_DQ_CONTROL_DEFINITIONS WHERE PLANTED_STORY IS NOT NULL) <> 5
       OR (SELECT COUNT(*) FROM STG_DQ_CONTROL_DEFINITIONS
           WHERE (CONTROL_ID = 'DQ-001' AND PLANTED_STORY = 'LEI nulls after onboarding migration; Equity Derivatives and Prime Services are the hotspots')
              OR (CONTROL_ID = 'DQ-010' AND PLANTED_STORY = 'UTI mismatch after TR vendor schema change and duplicate UTI hotfix; Rates and Credit are the hotspots')
              OR (CONTROL_ID = 'DQ-015' AND PLANTED_STORY = 'Scheduler failure caused late T+1 submissions on all desks; partial recovery 26-27 Oct')
              OR (CONTROL_ID = 'DQ-020' AND PLANTED_STORY = 'Commodities booking migration not mapped to risk feed; Commodities and Securitised are the hotspots')
              OR (CONTROL_ID = 'DQ-025' AND PLANTED_STORY = 'Gradual drift: vendor ISIN feed delayed; Equities Cash and Treasury are the hotspots')
          ) <> 5
       OR (SELECT MAX(LENGTH(PLANTED_STORY)) FROM STG_DQ_CONTROL_DEFINITIONS) <> 102
  );

  IF (NULLIF(TRIM(failure_list), '') IS NOT NULL) THEN
    EXECUTE IMMEDIATE
      'DECLARE preflight_failed EXCEPTION (-20001, ''Staging preflight failed: '
      || failure_list
      || '. Active tables were not modified.''); BEGIN RAISE preflight_failed; END;';
  END IF;

  BEGIN TRANSACTION;
  in_txn := TRUE;

  SELECT COALESCE(MAX(ACTIVE_DATASET_VERSION), 0) + 1
    INTO :new_version
  FROM DQ_DATASET_STATE;

  DELETE FROM DQ_RESULTS_BY_DESK;
  DELETE FROM DQ_EXCEPTIONS;
  DELETE FROM DQ_RESULTS;
  DELETE FROM ANALYST_COMMENTARY;
  DELETE FROM CHANGE_INCIDENT_EVENTS;
  DELETE FROM DQ_CONTROL_DEFINITIONS;
  DELETE FROM DESK_HIERARCHY;

  INSERT INTO DESK_HIERARCHY (
    DESK_ID, DESK_NAME, BUSINESS_LINE, PRIMARY_REGION, VOLUME_SHARE
  )
  SELECT DESK_ID, DESK_NAME, BUSINESS_LINE, PRIMARY_REGION, VOLUME_SHARE
  FROM STG_DESK_HIERARCHY;

  INSERT INTO DQ_CONTROL_DEFINITIONS (
    CONTROL_ID, CONTROL_NAME, DQ_DIMENSION, REGULATION, REGULATORY_REPORT,
    CRITICAL_DATA_ELEMENT, SOURCE_SYSTEM, FREQUENCY, GREEN_THRESHOLD,
    AMBER_THRESHOLD, SEVERITY, CHECK_LOGIC, BCBS239_PRINCIPLE, OWNER_ROLE,
    PLANTED_STORY
  )
  SELECT
    CONTROL_ID, CONTROL_NAME, DQ_DIMENSION, REGULATION, REGULATORY_REPORT,
    CRITICAL_DATA_ELEMENT, SOURCE_SYSTEM, FREQUENCY, GREEN_THRESHOLD,
    AMBER_THRESHOLD, SEVERITY, CHECK_LOGIC, BCBS239_PRINCIPLE, OWNER_ROLE,
    PLANTED_STORY
  FROM STG_DQ_CONTROL_DEFINITIONS;

  INSERT INTO DQ_RESULTS (
    RESULT_ID, METRIC_DATE, CONTROL_ID, FREQUENCY, TOTAL_RECORDS,
    FAILED_RECORDS, PASS_RATE_PCT, RAG_STATUS
  )
  SELECT
    RESULT_ID, METRIC_DATE, CONTROL_ID, FREQUENCY, TOTAL_RECORDS,
    FAILED_RECORDS, PASS_RATE_PCT, RAG_STATUS
  FROM STG_DQ_RESULTS;

  INSERT INTO DQ_RESULTS_BY_DESK (
    RESULT_ID, METRIC_DATE, CONTROL_ID, DESK_ID, TOTAL_RECORDS,
    FAILED_RECORDS, PASS_RATE_PCT, RAG_STATUS
  )
  SELECT
    RESULT_ID, METRIC_DATE, CONTROL_ID, DESK_ID, TOTAL_RECORDS,
    FAILED_RECORDS, PASS_RATE_PCT, RAG_STATUS
  FROM STG_DQ_RESULTS_BY_DESK;

  INSERT INTO DQ_EXCEPTIONS (
    EXCEPTION_ID, EXCEPTION_DATE, CONTROL_ID, DESK_ID, TRADE_ID, FIELD_NAME,
    OFFENDING_VALUE, FAILURE_REASON, SEVERITY, STATUS, AGEING_DAYS, ASSIGNED_TEAM
  )
  SELECT
    EXCEPTION_ID, EXCEPTION_DATE, CONTROL_ID, DESK_ID, TRADE_ID, FIELD_NAME,
    OFFENDING_VALUE, FAILURE_REASON, SEVERITY, STATUS, AGEING_DAYS, ASSIGNED_TEAM
  FROM STG_DQ_EXCEPTIONS;

  INSERT INTO CHANGE_INCIDENT_EVENTS (
    EVENT_ID, EVENT_DATE, EVENT_TYPE, DESK_IDS, DESCRIPTION, RELATED_CONTROL_ID
  )
  SELECT EVENT_ID, EVENT_DATE, EVENT_TYPE, DESK_IDS, DESCRIPTION, RELATED_CONTROL_ID
  FROM STG_CHANGE_INCIDENT_EVENTS;

  INSERT INTO ANALYST_COMMENTARY (
    COMMENTARY_DATE, CONTROL_ID, RAG_AT_TIME, ANALYST_COMMENTARY,
    ROOT_CAUSE_CATEGORY, PATH_TO_GREEN, AUTHOR_ROLE
  )
  SELECT
    COMMENTARY_DATE, CONTROL_ID, RAG_AT_TIME, ANALYST_COMMENTARY,
    ROOT_CAUSE_CATEGORY, PATH_TO_GREEN, AUTHOR_ROLE
  FROM STG_ANALYST_COMMENTARY;

  SELECT LISTAGG(check_name, ', ') WITHIN GROUP (ORDER BY check_name)
    INTO :published_list
  FROM (
    SELECT 'definition_without_result' AS check_name
    WHERE EXISTS (
      SELECT 1 FROM DQ_CONTROL_DEFINITIONS definition
      WHERE NOT EXISTS (
        SELECT 1 FROM DQ_RESULTS result WHERE result.CONTROL_ID = definition.CONTROL_ID
      )
    )
    UNION ALL
    SELECT 'desk_without_parent_result'
    WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS_BY_DESK desk
      WHERE NOT EXISTS (
        SELECT 1 FROM DQ_RESULTS result
        WHERE result.CONTROL_ID = desk.CONTROL_ID
          AND result.METRIC_DATE = desk.METRIC_DATE
      )
    )
    UNION ALL
    SELECT 'duplicate_desk_id'
    WHERE EXISTS (SELECT 1 FROM DESK_HIERARCHY GROUP BY DESK_ID HAVING COUNT(*) > 1)
    UNION ALL
    SELECT 'duplicate_desk_result_id'
    WHERE EXISTS (SELECT 1 FROM DQ_RESULTS_BY_DESK GROUP BY RESULT_ID HAVING COUNT(*) > 1)
    UNION ALL
    SELECT 'duplicate_exception_id'
    WHERE EXISTS (SELECT 1 FROM DQ_EXCEPTIONS GROUP BY EXCEPTION_ID HAVING COUNT(*) > 1)
    UNION ALL
    SELECT 'duplicate_trade_id'
    WHERE EXISTS (SELECT 1 FROM DQ_EXCEPTIONS GROUP BY TRADE_ID HAVING COUNT(*) > 1)
    UNION ALL
    SELECT 'duplicate_event_id'
    WHERE EXISTS (SELECT 1 FROM CHANGE_INCIDENT_EVENTS GROUP BY EVENT_ID HAVING COUNT(*) > 1)
    UNION ALL
    SELECT 'desk_record_counts'
    WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS_BY_DESK
      WHERE TOTAL_RECORDS <= 0 OR FAILED_RECORDS < 0 OR FAILED_RECORDS > TOTAL_RECORDS
    )
    UNION ALL
    SELECT 'pass_rate_bounds'
    WHERE EXISTS (
      SELECT 1 FROM DQ_RESULTS
      WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
      UNION ALL
      SELECT 1 FROM DQ_RESULTS_BY_DESK
      WHERE PASS_RATE_PCT < 0 OR PASS_RATE_PCT > 100
    )
    UNION ALL
    SELECT 'published_definition_count'
    WHERE (SELECT COUNT(*) FROM DQ_CONTROL_DEFINITIONS) <> (SELECT COUNT(*) FROM STG_DQ_CONTROL_DEFINITIONS)
    UNION ALL
    SELECT 'published_desk_count'
    WHERE (SELECT COUNT(*) FROM DESK_HIERARCHY) <> (SELECT COUNT(*) FROM STG_DESK_HIERARCHY)
    UNION ALL
    SELECT 'published_result_count'
    WHERE (SELECT COUNT(*) FROM DQ_RESULTS) <> (SELECT COUNT(*) FROM STG_DQ_RESULTS)
    UNION ALL
    SELECT 'published_desk_result_count'
    WHERE (SELECT COUNT(*) FROM DQ_RESULTS_BY_DESK) <> (SELECT COUNT(*) FROM STG_DQ_RESULTS_BY_DESK)
    UNION ALL
    SELECT 'published_exception_count'
    WHERE (SELECT COUNT(*) FROM DQ_EXCEPTIONS) <> (SELECT COUNT(*) FROM STG_DQ_EXCEPTIONS)
    UNION ALL
    SELECT 'published_event_count'
    WHERE (SELECT COUNT(*) FROM CHANGE_INCIDENT_EVENTS) <> (SELECT COUNT(*) FROM STG_CHANGE_INCIDENT_EVENTS)
    UNION ALL
    SELECT 'published_commentary_count'
    WHERE (SELECT COUNT(*) FROM ANALYST_COMMENTARY) <> (SELECT COUNT(*) FROM STG_ANALYST_COMMENTARY)
  );

  IF (NULLIF(TRIM(published_list), '') IS NOT NULL) THEN
    EXECUTE IMMEDIATE
      'DECLARE published_failed EXCEPTION (-20004, ''Published rows failed checks after replace: '
      || published_list
      || '. Transaction rolled back. DQ_DATASET_STATE was not updated.''); BEGIN RAISE published_failed; END;';
  END IF;

  -- Full reseed: every control in this rebuild is affected, so each matched version increments.
  -- A future incremental load should merge only the controls whose inputs changed.
  MERGE INTO DQ_CONTROL_SNAPSHOT AS target
  USING (
    WITH latest AS (
    SELECT
      CONTROL_ID,
      METRIC_DATE,
      PASS_RATE_PCT,
      RAG_STATUS,
      FAILED_RECORDS,
      TOTAL_RECORDS,
      ROW_NUMBER() OVER (PARTITION BY CONTROL_ID ORDER BY METRIC_DATE DESC) AS RN
    FROM DQ_RESULTS
  ),
  reds AS (
    SELECT
      CONTROL_ID,
      MIN(METRIC_DATE) AS FIRST_RED_DATE,
      MAX(METRIC_DATE) AS LAST_RED_DATE
    FROM DQ_RESULTS
    WHERE RAG_STATUS = 'Red'
    GROUP BY CONTROL_ID
  ),
  points AS (
    SELECT CONTROL_ID, COUNT(*) AS POINT_COUNT
    FROM DQ_RESULTS
    GROUP BY CONTROL_ID
  ),
  desk_controls AS (
    SELECT DISTINCT CONTROL_ID
    FROM DQ_RESULTS_BY_DESK
  ),
  exception_stats AS (
    SELECT
      CONTROL_ID,
      COUNT(*) AS EXCEPTION_COUNT,
      COUNT_IF(STATUS = 'Open') AS OPEN_EXCEPTION_COUNT,
      MAX(IFF(STATUS = 'Open', AGEING_DAYS, NULL)) AS OLDEST_OPEN_AGEING_DAYS
    FROM DQ_EXCEPTIONS
    GROUP BY CONTROL_ID
  ),
  event_stats AS (
    SELECT RELATED_CONTROL_ID AS CONTROL_ID, COUNT(*) AS EVENT_COUNT
    FROM CHANGE_INCIDENT_EVENTS
    GROUP BY RELATED_CONTROL_ID
  ),
  commentary_stats AS (
    SELECT CONTROL_ID, COUNT(*) AS COMMENTARY_COUNT
    FROM ANALYST_COMMENTARY
    GROUP BY CONTROL_ID
  )
    SELECT
      definition.CONTROL_ID,
      :new_version AS DATASET_VERSION,
      'dq-rag-v1' AS CALCULATION_VERSION,
      SYSDATE() AS CALCULATED_AT,
      latest.METRIC_DATE AS AS_OF_DATE,
      latest.PASS_RATE_PCT,
      latest.RAG_STATUS,
      latest.FAILED_RECORDS,
      latest.TOTAL_RECORDS,
      definition.GREEN_THRESHOLD,
      definition.AMBER_THRESHOLD,
      definition.FREQUENCY,
      reds.FIRST_RED_DATE,
      reds.LAST_RED_DATE,
      points.POINT_COUNT,
      desk_controls.CONTROL_ID IS NOT NULL AS HAS_DESK_SPLIT,
      COALESCE(latest.RAG_STATUS = 'Green' AND reds.FIRST_RED_DATE IS NOT NULL, FALSE) AS RECOVERED,
      COALESCE(exception_stats.EXCEPTION_COUNT, 0) AS EXCEPTION_COUNT,
      COALESCE(exception_stats.OPEN_EXCEPTION_COUNT, 0) AS OPEN_EXCEPTION_COUNT,
      exception_stats.OLDEST_OPEN_AGEING_DAYS,
      COALESCE(event_stats.EVENT_COUNT, 0) AS EVENT_COUNT,
      COALESCE(commentary_stats.COMMENTARY_COUNT, 0) AS COMMENTARY_COUNT
    FROM DQ_CONTROL_DEFINITIONS definition
  JOIN latest
    ON latest.CONTROL_ID = definition.CONTROL_ID
   AND latest.RN = 1
  JOIN points
    ON points.CONTROL_ID = definition.CONTROL_ID
  LEFT JOIN reds
    ON reds.CONTROL_ID = definition.CONTROL_ID
  LEFT JOIN desk_controls
    ON desk_controls.CONTROL_ID = definition.CONTROL_ID
  LEFT JOIN exception_stats
    ON exception_stats.CONTROL_ID = definition.CONTROL_ID
  LEFT JOIN event_stats
    ON event_stats.CONTROL_ID = definition.CONTROL_ID
    LEFT JOIN commentary_stats
      ON commentary_stats.CONTROL_ID = definition.CONTROL_ID
  ) AS source
  ON target.CONTROL_ID = source.CONTROL_ID
  WHEN MATCHED THEN UPDATE SET
    CONTROL_DATA_VERSION = target.CONTROL_DATA_VERSION + 1,
    DATASET_VERSION = source.DATASET_VERSION,
    CALCULATION_VERSION = source.CALCULATION_VERSION,
    CALCULATED_AT = source.CALCULATED_AT,
    AS_OF_DATE = source.AS_OF_DATE,
    PASS_RATE_PCT = source.PASS_RATE_PCT,
    RAG_STATUS = source.RAG_STATUS,
    FAILED_RECORDS = source.FAILED_RECORDS,
    TOTAL_RECORDS = source.TOTAL_RECORDS,
    GREEN_THRESHOLD = source.GREEN_THRESHOLD,
    AMBER_THRESHOLD = source.AMBER_THRESHOLD,
    FREQUENCY = source.FREQUENCY,
    FIRST_RED_DATE = source.FIRST_RED_DATE,
    LAST_RED_DATE = source.LAST_RED_DATE,
    POINT_COUNT = source.POINT_COUNT,
    HAS_DESK_SPLIT = source.HAS_DESK_SPLIT,
    RECOVERED = source.RECOVERED,
    EXCEPTION_COUNT = source.EXCEPTION_COUNT,
    OPEN_EXCEPTION_COUNT = source.OPEN_EXCEPTION_COUNT,
    OLDEST_OPEN_AGEING_DAYS = source.OLDEST_OPEN_AGEING_DAYS,
    EVENT_COUNT = source.EVENT_COUNT,
    COMMENTARY_COUNT = source.COMMENTARY_COUNT
  WHEN NOT MATCHED THEN INSERT (
    CONTROL_ID, CONTROL_DATA_VERSION, DATASET_VERSION, CALCULATION_VERSION, CALCULATED_AT,
    AS_OF_DATE, PASS_RATE_PCT, RAG_STATUS, FAILED_RECORDS, TOTAL_RECORDS, GREEN_THRESHOLD,
    AMBER_THRESHOLD, FREQUENCY, FIRST_RED_DATE, LAST_RED_DATE, POINT_COUNT,
    HAS_DESK_SPLIT, RECOVERED, EXCEPTION_COUNT, OPEN_EXCEPTION_COUNT,
    OLDEST_OPEN_AGEING_DAYS, EVENT_COUNT, COMMENTARY_COUNT
  ) VALUES (
    source.CONTROL_ID, 1, source.DATASET_VERSION, source.CALCULATION_VERSION, source.CALCULATED_AT,
    source.AS_OF_DATE, source.PASS_RATE_PCT, source.RAG_STATUS, source.FAILED_RECORDS, source.TOTAL_RECORDS,
    source.GREEN_THRESHOLD, source.AMBER_THRESHOLD, source.FREQUENCY, source.FIRST_RED_DATE, source.LAST_RED_DATE,
    source.POINT_COUNT, source.HAS_DESK_SPLIT, source.RECOVERED, source.EXCEPTION_COUNT, source.OPEN_EXCEPTION_COUNT,
    source.OLDEST_OPEN_AGEING_DAYS, source.EVENT_COUNT, source.COMMENTARY_COUNT
  );

  DELETE FROM DQ_CONTROL_SNAPSHOT
  WHERE NOT EXISTS (
    SELECT 1
    FROM DQ_CONTROL_DEFINITIONS definition
    WHERE definition.CONTROL_ID = DQ_CONTROL_SNAPSHOT.CONTROL_ID
  );

  SELECT COUNT(*)
    INTO :snapshot_gap
  FROM DQ_CONTROL_DEFINITIONS definition
  WHERE EXISTS (
    SELECT 1 FROM DQ_RESULTS result WHERE result.CONTROL_ID = definition.CONTROL_ID
  )
  AND NOT EXISTS (
    SELECT 1 FROM DQ_CONTROL_SNAPSHOT snapshot WHERE snapshot.CONTROL_ID = definition.CONTROL_ID
  );

  SELECT COUNT(*)
    INTO :snapshot_mismatch
  FROM DQ_CONTROL_SNAPSHOT snapshot
  WHERE snapshot.CONTROL_DATA_VERSION < 1
     OR snapshot.CALCULATION_VERSION <> 'dq-rag-v1'
     OR snapshot.DATASET_VERSION <> :new_version
     OR snapshot.RAG_STATUS <> CASE
          WHEN snapshot.PASS_RATE_PCT >= snapshot.GREEN_THRESHOLD THEN 'Green'
          WHEN snapshot.PASS_RATE_PCT >= snapshot.AMBER_THRESHOLD THEN 'Amber'
          ELSE 'Red'
        END
     OR snapshot.RECOVERED <> COALESCE(snapshot.RAG_STATUS = 'Green' AND snapshot.FIRST_RED_DATE IS NOT NULL, FALSE);

  SELECT COUNT(*)
    INTO :snapshot_count
  FROM DQ_CONTROL_SNAPSHOT;

  SELECT COUNT(*)
    INTO :snapshot_missing
  FROM (
    SELECT CONTROL_ID FROM DQ_CONTROL_DEFINITIONS
    MINUS
    SELECT CONTROL_ID FROM DQ_CONTROL_SNAPSHOT
  );

  IF (snapshot_count <> 36 OR snapshot_missing <> 0 OR snapshot_gap <> 0 OR snapshot_mismatch <> 0) THEN
    EXECUTE IMMEDIATE
      'DECLARE snapshot_failed EXCEPTION (-20002, ''Snapshot rebuild failed dq-rag-v1. Expected 36 controls, count='
      || snapshot_count::VARCHAR
      || '. Transaction rolled back. DQ_DATASET_STATE was not updated.''); BEGIN RAISE snapshot_failed; END;';
  END IF;

  -- Published source rows and the snapshot are in this transaction.
  -- The active dataset version is written next, and only then committed.
  MERGE INTO DQ_DATASET_STATE AS target
  USING (
    SELECT
      1 AS STATE_ID,
      :new_version AS ACTIVE_DATASET_VERSION,
      :source_label AS SOURCE_LABEL,
      'SUCCEEDED' AS LOAD_STATUS,
      :started_at AS STARTED_AT,
      SYSDATE() AS COMPLETED_AT,
      (SELECT COUNT(*) FROM DQ_CONTROL_DEFINITIONS) AS DEFINITION_ROWS,
      (SELECT COUNT(*) FROM DQ_RESULTS) AS RESULT_ROWS,
      (SELECT COUNT(*) FROM DQ_RESULTS_BY_DESK) AS DESK_RESULT_ROWS,
      (SELECT COUNT(*) FROM DQ_EXCEPTIONS) AS EXCEPTION_ROWS,
      (SELECT COUNT(*) FROM DESK_HIERARCHY) AS DESK_ROWS,
      (SELECT COUNT(*) FROM CHANGE_INCIDENT_EVENTS) AS EVENT_ROWS,
      (SELECT COUNT(*) FROM ANALYST_COMMENTARY) AS COMMENTARY_ROWS,
      (SELECT MIN(METRIC_DATE) FROM DQ_RESULTS) AS METRIC_DATE_MIN,
      (SELECT MAX(METRIC_DATE) FROM DQ_RESULTS) AS METRIC_DATE_MAX
  ) AS source
  ON target.STATE_ID = source.STATE_ID
  WHEN MATCHED THEN UPDATE SET
    ACTIVE_DATASET_VERSION = source.ACTIVE_DATASET_VERSION,
    SOURCE_LABEL = source.SOURCE_LABEL,
    LOAD_STATUS = source.LOAD_STATUS,
    STARTED_AT = source.STARTED_AT,
    COMPLETED_AT = source.COMPLETED_AT,
    DEFINITION_ROWS = source.DEFINITION_ROWS,
    RESULT_ROWS = source.RESULT_ROWS,
    DESK_RESULT_ROWS = source.DESK_RESULT_ROWS,
    EXCEPTION_ROWS = source.EXCEPTION_ROWS,
    DESK_ROWS = source.DESK_ROWS,
    EVENT_ROWS = source.EVENT_ROWS,
    COMMENTARY_ROWS = source.COMMENTARY_ROWS,
    METRIC_DATE_MIN = source.METRIC_DATE_MIN,
    METRIC_DATE_MAX = source.METRIC_DATE_MAX
  WHEN NOT MATCHED THEN INSERT (
    STATE_ID, ACTIVE_DATASET_VERSION, SOURCE_LABEL, LOAD_STATUS, STARTED_AT,
    COMPLETED_AT, DEFINITION_ROWS, RESULT_ROWS, DESK_RESULT_ROWS, EXCEPTION_ROWS,
    DESK_ROWS, EVENT_ROWS, COMMENTARY_ROWS, METRIC_DATE_MIN, METRIC_DATE_MAX
  ) VALUES (
    source.STATE_ID, source.ACTIVE_DATASET_VERSION, source.SOURCE_LABEL, source.LOAD_STATUS,
    source.STARTED_AT, source.COMPLETED_AT, source.DEFINITION_ROWS, source.RESULT_ROWS,
    source.DESK_RESULT_ROWS, source.EXCEPTION_ROWS, source.DESK_ROWS, source.EVENT_ROWS,
    source.COMMENTARY_ROWS, source.METRIC_DATE_MIN, source.METRIC_DATE_MAX
  );

  COMMIT;
  in_txn := FALSE;
  RETURN 'Reseed committed. ACTIVE_DATASET_VERSION = ' || new_version::VARCHAR;
EXCEPTION
  WHEN OTHER THEN
    -- Any failure after BEGIN TRANSACTION lands here with in_txn still true.
    -- COMMIT is the only statement that clears that flag.
    IF (in_txn) THEN
      ROLLBACK;
    END IF;
    RAISE;
END;
