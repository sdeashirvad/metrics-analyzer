-- Portfolio snapshot and organisation summary.
-- Built only from V_APPLICATION_MONTH_STATUS. Counts and sums the view already exposes.
-- No compliance percentage, numerator, denominator, compliant/pending/NA application count, or risk score.
-- Refresh replaces rows for dataset version v1-seed20261103. Safe to rerun.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE METRICS_ANALYZER;
USE SCHEMA METRICS_ANALYZER.MOCK_DATA;

CREATE TABLE IF NOT EXISTS APP_PORTFOLIO_MONTHLY_SNAPSHOT (
    REPORTING_MONTHEND_DATE DATE NOT NULL,
    DATASET_VERSION VARCHAR NOT NULL,
    APPLICATIONS_REPORTING NUMBER NOT NULL,
    NON_COMPLIANT_APPLICATIONS NUMBER NOT NULL,
    APPLICATIONS_WITHOUT_COMPLETED_TEST NUMBER NOT NULL,
    APPLICATIONS_WITH_FAILED_TEST NUMBER NOT NULL,
    NEWLY_NON_COMPLIANT NUMBER NOT NULL,
    RESOLVED NUMBER NOT NULL,
    PERSISTENT_NON_COMPLIANT NUMBER NOT NULL,
    NO_PRIOR_MONTH NUMBER NOT NULL,
    NOT_NON_COMPLIANT_BOTH_MONTHS NUMBER NOT NULL,
    METRIC_ROWS NUMBER NOT NULL,
    OPEN_FINDINGS NUMBER NOT NULL,
    SNAPSHOT_GENERATED_AT TIMESTAMP_LTZ NOT NULL,
    SOURCE_VIEW VARCHAR NOT NULL,
    SOURCE_ROW_COUNT NUMBER NOT NULL,
    CONSTRAINT PK_APP_PORTFOLIO_MONTHLY_SNAPSHOT PRIMARY KEY (REPORTING_MONTHEND_DATE, DATASET_VERSION)
)
COMMENT = 'One row per reporting month and dataset version. Application counts come from V_APPLICATION_MONTH_STATUS. OPEN_FINDINGS is the sum of the per-application monthly value, not a sum of TOTAL_RFB across metric rows.';

DELETE FROM APP_PORTFOLIO_MONTHLY_SNAPSHOT WHERE DATASET_VERSION = 'v1-seed20261103';

INSERT INTO APP_PORTFOLIO_MONTHLY_SNAPSHOT (
    REPORTING_MONTHEND_DATE, DATASET_VERSION,
    APPLICATIONS_REPORTING, NON_COMPLIANT_APPLICATIONS,
    APPLICATIONS_WITHOUT_COMPLETED_TEST, APPLICATIONS_WITH_FAILED_TEST,
    NEWLY_NON_COMPLIANT, RESOLVED, PERSISTENT_NON_COMPLIANT, NO_PRIOR_MONTH, NOT_NON_COMPLIANT_BOTH_MONTHS,
    METRIC_ROWS, OPEN_FINDINGS,
    SNAPSHOT_GENERATED_AT, SOURCE_VIEW, SOURCE_ROW_COUNT
)
SELECT
    REPORTING_MONTHEND_DATE,
    'v1-seed20261103',
    COUNT(*),
    SUM(IS_NON_COMPLIANT_APP),
    SUM(HAS_NO_COMPLETED_TEST),
    SUM(HAS_FAILED_TEST),
    COUNT_IF(MOVEMENT_STATUS = 'NEWLY_NON_COMPLIANT'),
    COUNT_IF(MOVEMENT_STATUS = 'RESOLVED'),
    COUNT_IF(MOVEMENT_STATUS = 'PERSISTENT_NON_COMPLIANT'),
    COUNT_IF(MOVEMENT_STATUS = 'NO_PRIOR_MONTH'),
    COUNT_IF(MOVEMENT_STATUS = 'NOT_NON_COMPLIANT_BOTH_MONTHS'),
    SUM(METRIC_ROWS),
    SUM(OPEN_FINDINGS),
    CURRENT_TIMESTAMP(),
    'METRICS_ANALYZER.MOCK_DATA.V_APPLICATION_MONTH_STATUS',
    (SELECT COUNT(*) FROM V_APPLICATION_MONTH_STATUS)
FROM V_APPLICATION_MONTH_STATUS
GROUP BY REPORTING_MONTHEND_DATE;

-- HIERARCHY_NAME separates the two trees. Filter to one value. Do not join BUSINESS_ORG rows to BU rows.
CREATE OR REPLACE VIEW V_ORGANIZATION_MONTHLY_SUMMARY
COMMENT = 'Monthly application counts for one organisation tree at a time. HIERARCHY_NAME is BUSINESS_ORG or BU. Level columns mean different source fields in each tree and must not be joined across trees.'
AS
SELECT
    'BUSINESS_ORG' AS HIERARCHY_NAME,
    REPORTING_MONTHEND_DATE,
    SUPER_DIVISION AS LEVEL_1,
    DIVISION AS LEVEL_2,
    SUPER_DEPARTMENT AS LEVEL_3,
    DEPARTMENT AS LEVEL_4,
    BUS_ORG_LG_NM AS LEVEL_5,
    COUNT(*) AS APPLICATIONS_REPORTING,
    SUM(IS_NON_COMPLIANT_APP) AS NON_COMPLIANT_APPLICATIONS,
    SUM(HAS_NO_COMPLETED_TEST) AS APPLICATIONS_WITHOUT_COMPLETED_TEST,
    SUM(HAS_FAILED_TEST) AS APPLICATIONS_WITH_FAILED_TEST,
    COUNT_IF(MOVEMENT_STATUS = 'NEWLY_NON_COMPLIANT') AS NEWLY_NON_COMPLIANT,
    COUNT_IF(MOVEMENT_STATUS = 'RESOLVED') AS RESOLVED,
    COUNT_IF(MOVEMENT_STATUS = 'PERSISTENT_NON_COMPLIANT') AS PERSISTENT_NON_COMPLIANT,
    COUNT_IF(MOVEMENT_STATUS = 'NO_PRIOR_MONTH') AS NO_PRIOR_MONTH,
    COUNT_IF(MOVEMENT_STATUS = 'NOT_NON_COMPLIANT_BOTH_MONTHS') AS NOT_NON_COMPLIANT_BOTH_MONTHS,
    SUM(METRIC_ROWS) AS METRIC_ROWS,
    SUM(OPEN_FINDINGS) AS OPEN_FINDINGS
FROM V_APPLICATION_MONTH_STATUS
GROUP BY REPORTING_MONTHEND_DATE, SUPER_DIVISION, DIVISION, SUPER_DEPARTMENT, DEPARTMENT, BUS_ORG_LG_NM
UNION ALL
SELECT
    'BU',
    REPORTING_MONTHEND_DATE,
    BU_SUPER_DIVISION,
    BU_DIVISION,
    BU_SUPER_DEPARTMENT,
    BU_DEPARTMENT,
    NULL,
    COUNT(*),
    SUM(IS_NON_COMPLIANT_APP),
    SUM(HAS_NO_COMPLETED_TEST),
    SUM(HAS_FAILED_TEST),
    COUNT_IF(MOVEMENT_STATUS = 'NEWLY_NON_COMPLIANT'),
    COUNT_IF(MOVEMENT_STATUS = 'RESOLVED'),
    COUNT_IF(MOVEMENT_STATUS = 'PERSISTENT_NON_COMPLIANT'),
    COUNT_IF(MOVEMENT_STATUS = 'NO_PRIOR_MONTH'),
    COUNT_IF(MOVEMENT_STATUS = 'NOT_NON_COMPLIANT_BOTH_MONTHS'),
    SUM(METRIC_ROWS),
    SUM(OPEN_FINDINGS)
FROM V_APPLICATION_MONTH_STATUS
GROUP BY REPORTING_MONTHEND_DATE, BU_SUPER_DIVISION, BU_DIVISION, BU_SUPER_DEPARTMENT, BU_DEPARTMENT;

SELECT COUNT(*) AS snapshot_rows, SUM(APPLICATIONS_REPORTING) AS app_months, MIN(SOURCE_ROW_COUNT) AS source_row_count
FROM APP_PORTFOLIO_MONTHLY_SNAPSHOT
WHERE DATASET_VERSION = 'v1-seed20261103';

SELECT REPORTING_MONTHEND_DATE, APPLICATIONS_REPORTING, NON_COMPLIANT_APPLICATIONS, NEWLY_NON_COMPLIANT, RESOLVED, METRIC_ROWS, OPEN_FINDINGS
FROM APP_PORTFOLIO_MONTHLY_SNAPSHOT
WHERE DATASET_VERSION = 'v1-seed20261103' AND REPORTING_MONTHEND_DATE = '2026-10-31';

SELECT HIERARCHY_NAME, COUNT(*) AS org_rows, SUM(APPLICATIONS_REPORTING) AS app_months
FROM V_ORGANIZATION_MONTHLY_SUMMARY
GROUP BY HIERARCHY_NAME
ORDER BY HIERARCHY_NAME;
