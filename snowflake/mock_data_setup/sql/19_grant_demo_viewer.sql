-- Minimum read and agent-use grants for the existing role METRICS_ANALYZER_DEMO_VIEWER.
-- The role already exists and is already granted to user METRICS_ANALYZER_VIEWER.
-- There is no user named DEMO_VIEWER. This script does not create a user or a role.
-- It does not grant MOCK_DATA objects to any other role, and it does not change DQ grants.
-- MONITOR is not granted. SNOWFLAKE.CORTEX_USER is not granted; the role already has
-- SNOWFLAKE.CORTEX_AGENT_USER, and PUBLIC already has SNOWFLAKE.CORTEX_USER.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

GRANT USAGE ON SCHEMA METRICS_ANALYZER.MOCK_DATA TO ROLE METRICS_ANALYZER_DEMO_VIEWER;

GRANT SELECT ON TABLE METRICS_ANALYZER.MOCK_DATA.APPLICATION_COMPLIANCE TO ROLE METRICS_ANALYZER_DEMO_VIEWER;
GRANT SELECT ON VIEW METRICS_ANALYZER.MOCK_DATA.V_APPLICATION_MONTH_STATUS TO ROLE METRICS_ANALYZER_DEMO_VIEWER;
GRANT SELECT ON SEMANTIC VIEW METRICS_ANALYZER.MOCK_DATA.SV_APPLICATION_COMPLIANCE_V1 TO ROLE METRICS_ANALYZER_DEMO_VIEWER;

GRANT USAGE ON AGENT METRICS_ANALYZER.MOCK_DATA.AGENT_APPLICATION_COMPLIANCE_V1 TO ROLE METRICS_ANALYZER_DEMO_VIEWER;
GRANT USAGE ON AGENT METRICS_ANALYZER.MOCK_DATA.AGENT_APPLICATION_TEXT_TO_SQL_V1 TO ROLE METRICS_ANALYZER_DEMO_VIEWER;

SHOW GRANTS TO ROLE METRICS_ANALYZER_DEMO_VIEWER;
