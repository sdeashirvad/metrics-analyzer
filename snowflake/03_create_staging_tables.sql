-- Load mechanics for the CSV workflow in README.md. Not analytical tables.
-- CREATE OR REPLACE so a re-run picks up SKIP_BYTE_ORDER_MARK. This does not touch permanent tables.
-- Date values are converted in the COPY SELECT, not by DATE_FORMAT.
CREATE OR REPLACE FILE FORMAT DQ_CSV_FORMAT
  TYPE = CSV
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ESCAPE = NONE
  ESCAPE_UNENCLOSED_FIELD = NONE
  SKIP_HEADER = 1
  SKIP_BYTE_ORDER_MARK = TRUE
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('')
  TRIM_SPACE = TRUE
  ENCODING = 'UTF8'
  DATE_FORMAT = 'YYYY-MM-DD'
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
  COMMENT = 'Excel CSV extracts. Header row skipped. Embedded quotes are doubled. UTF-8 BOM skipped.';

CREATE STAGE IF NOT EXISTS DQ_CSV_STAGE
  FILE_FORMAT = DQ_CSV_FORMAT
  COMMENT = 'CSV extracts of SMARTS_DQ_mock_data.xlsx plus planted_story.csv.';
