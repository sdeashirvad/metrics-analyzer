    IFF(REGEXP_LIKE(r.METRIC_DATE, '[0-9]{4}-[0-9]{2}-[0-9]{2}'), TRY_TO_DATE(r.METRIC_DATE, 'YYYY-MM-DD'), NULL),
    r.METRIC_DATE_TYPE,
    IFF(REGEXP_LIKE(r.IS_NUMERATOR, '[0-9]+'), TRY_TO_NUMBER(r.IS_NUMERATOR), NULL),
